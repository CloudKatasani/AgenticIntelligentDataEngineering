"""Deterministic reading of file inputs.

The profiler exists so that no statistic about a table is generated by a model.
This is the same rule applied to files: line counts, detected dialects, the
table names a SQL script touches, the column cardinalities in a metering export
— all computed here, then handed to the model as facts it must not recompute.

Nothing here parses a language completely. A COBOL copybook parser and a
full SQL grammar are not what makes the output trustworthy; what makes it
trustworthy is that the numbers come from counting rather than from prose, and
that every extracted reference can be pointed back at a file and a line.
"""

from __future__ import annotations

import csv
import io
import re
from collections import Counter
from dataclasses import dataclass, field
from typing import Any

from app.domain.document import DocumentContent

MAX_EXCERPT_CHARS = 12_000
"""Per file. Enough for a model to reason about a stored procedure; small
enough that twenty files do not blow the context window on their own."""

MAX_TOTAL_EXCERPT_CHARS = 120_000

# Language detection by extension. Deliberately coarse — the point is to tell
# the model what it is looking at, not to be a linguist.
_LANGUAGES: dict[str, str] = {
    ".sql": "SQL", ".ddl": "SQL DDL", ".hql": "HiveQL",
    ".py": "Python", ".scala": "Scala", ".java": "Java", ".sas": "SAS",
    ".cbl": "COBOL", ".cob": "COBOL", ".cpy": "COBOL copybook",
    ".jcl": "JCL", ".prc": "Stored procedure",
    ".dtsx": "SSIS package (XML)", ".ktr": "Pentaho transformation (XML)",
    ".kjb": "Pentaho job (XML)", ".xml": "XML",
    ".json": "JSON", ".jsonl": "JSON Lines", ".yaml": "YAML", ".yml": "YAML",
    ".csv": "CSV", ".tsv": "TSV", ".md": "Markdown", ".txt": "Text",
    ".log": "Log", ".docx": "Word document", ".pdf": "PDF", ".xlsx": "Excel workbook",
}

_BINARY_EXTENSIONS = {".pdf", ".docx", ".xlsx", ".parquet"}

# SQL object references. Case-insensitive, tolerant of quoting and of the
# schema-qualified names that matter for lineage.
_TABLE_PATTERN = re.compile(
    r"\b(?:from|join|into|update|table|merge\s+into)\s+"
    r"([`\"\[]?[A-Za-z_][\w$]*[`\"\]]?(?:\.[`\"\[]?[A-Za-z_][\w$]*[`\"\]]?){0,2})",
    re.IGNORECASE,
)
_CREATE_PATTERN = re.compile(
    r"\bcreate\s+(?:or\s+replace\s+)?(?:temp(?:orary)?\s+)?"
    r"(table|view|materialized\s+view|procedure|function)\s+"
    r"([`\"\[]?[A-Za-z_][\w$]*[`\"\]]?(?:\.[`\"\[]?[A-Za-z_][\w$]*[`\"\]]?){0,2})",
    re.IGNORECASE,
)
_COPYBOOK_FIELD = re.compile(r"^\s*(\d{2})\s+([A-Z0-9-]+)\s*(?:PIC\s+([^\s.]+))?", re.MULTILINE)

_SQL_KEYWORDS = {"select", "where", "group", "order", "set", "values", "as", "on", "using"}


@dataclass
class ArtifactFacts:
    """What was counted in one file."""

    name: str
    path: str
    space: str
    size_bytes: int
    language: str
    line_count: int = 0
    is_binary: bool = False
    excerpt: str = ""
    truncated: bool = False
    sha256: str = ""
    findings: dict[str, Any] = field(default_factory=dict)
    """Language-specific counted facts: table references, field definitions,
    column statistics. Keyed by what it is, so the prompt can render it."""

    def as_dict(self) -> dict[str, Any]:
        return {
            "file": self.name,
            "path": self.path,
            "space": self.space,
            "language": self.language,
            "size_bytes": self.size_bytes,
            "line_count": self.line_count,
            "sha256": self.sha256,
            "truncated": self.truncated,
            **({"findings": self.findings} if self.findings else {}),
        }


def read_artifact(content: DocumentContent, *, space_name: str = "") -> ArtifactFacts:
    """Count what can be counted in one file."""
    import hashlib

    ref = content.ref
    extension = ref.extension
    language = _LANGUAGES.get(extension, extension.lstrip(".").upper() or "Unknown")
    facts = ArtifactFacts(
        name=ref.name,
        path=ref.path or ref.name,
        space=space_name or ref.space_id,
        size_bytes=len(content.data),
        language=language,
        sha256=hashlib.sha256(content.data).hexdigest()[:16],
    )

    if extension in _BINARY_EXTENSIONS:
        facts.is_binary = True
        text = _extract_binary_text(content.data, extension)
        if not text:
            facts.excerpt = ""
            facts.findings["note"] = (
                f"{language} content could not be extracted as text on this deployment; "
                "the file is recorded but not read."
            )
            return facts
    else:
        text = content.data.decode("utf-8", errors="replace")

    facts.line_count = text.count("\n") + 1 if text else 0
    facts.excerpt = text[:MAX_EXCERPT_CHARS]
    facts.truncated = len(text) > MAX_EXCERPT_CHARS

    if extension in {".sql", ".ddl", ".hql", ".prc"}:
        facts.findings.update(_sql_facts(text))
    elif extension in {".cbl", ".cob", ".cpy"}:
        facts.findings.update(_copybook_facts(text))
    elif extension in {".csv", ".tsv"}:
        facts.findings.update(_delimited_facts(text, delimiter="\t" if extension == ".tsv" else ","))
    elif extension in {".xml", ".dtsx", ".ktr", ".kjb"}:
        facts.findings.update(_xml_facts(text))

    return facts


